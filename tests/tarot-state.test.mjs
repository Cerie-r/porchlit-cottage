import assert from 'node:assert/strict';
import {tarotCards,shuffleDeck,interpretationText,positions} from '../src/tarot-state.js';
assert.equal(tarotCards.length,78);
assert.equal(new Set(tarotCards.map(c=>c.id)).size,78);
assert.equal(tarotCards.filter(c=>c.suit==='major').length,22);
for(const suit of ['wand','cup','sword','coin'])assert.equal(tarotCards.filter(c=>c.suit===suit).length,14);
const original=JSON.stringify(tarotCards);
let seed=534;const rng=()=>((seed=(seed*16807)%2147483647)/2147483647);
const shuffled=shuffleDeck(true,rng);
assert.equal(new Set(shuffled.map(c=>c.id)).size,78);
assert.notDeepEqual(shuffled.map(c=>c.id),tarotCards.map(c=>c.id));
assert.ok(shuffled.some(c=>c.reversed));assert.ok(shuffled.some(c=>!c.reversed));
assert.ok(shuffleDeck(false,rng).every(c=>!c.reversed));
assert.equal(JSON.stringify(tarotCards),original);
const draw=shuffled.slice(0,3),snapshot=JSON.stringify(draw);
const text=interpretationText('只属于本轮的问题',draw,false);
assert.ok(!text.includes('只属于本轮的问题'));
draw.forEach((c,i)=>assert.ok(text.includes(`${positions(3)[i]}：${c.name}（${c.reversed?'逆位':'正位'}）`)));
assert.equal(JSON.stringify(draw),snapshot);
assert.ok(interpretationText('',draw).includes('没有提供问题'));
assert.ok(interpretationText('我的问题',draw,true).includes('我的问题'));
console.log('Tarot: 78 unique cards, stable order/orientations, optional question sharing passed');
