import assert from 'node:assert/strict';
import {targetsFor,applyDecor,applyPreset,presets,keyFor,decorValue,roomFor} from '../src/decor-state.js';
const base={values:{'sofa|paint':'#123456'},locks:{'sofa|paint':true}};
const cabinets=targetsFor({room:'downstairs',scope:'room',part:'paint',group:'cabinet'});
assert.ok(cabinets.includes('refrigerator')&&cabinets.includes('tvUnit'));
assert.ok(!cabinets.includes('sofa')&&!cabinets.includes('bedroomWardrobe'));
const paint=applyDecor(base,cabinets,'paint','#eeeeee');
assert.equal(decorValue(paint,'sofa','paint'), '#123456');
assert.equal(decorValue(paint,'refrigerator','paint'),'#eeeeee');
assert.equal(decorValue(paint,'refrigerator','detail'),undefined,'paint does not recolor handles');
const cloth=applyDecor(paint,targetsFor({owner:'sofa',scope:'one',part:'fabric:pillow'}),'fabric:pillow','blue');
assert.equal(decorValue(cloth,'sofa','fabric:pillow'),'blue');
assert.equal(decorValue(cloth,'sofa','fabric:fabric'),undefined,'pillows independent from seat');
const bundle=applyPreset(base,presets.blue,{room:'downstairs',scope:'room',groups:['frame','fabric','wall']});
assert.equal(decorValue(bundle,'sofa','paint'),'#123456','preset respects locks');
assert.equal(decorValue(bundle,'room:downstairs','wall'),'blue');
assert.equal(decorValue(bundle,'bedroomBed','fabric:quilt'),undefined,'room limits preserved');
assert.equal(decorValue(bundle,'tvUnit','paint'),undefined,'unchecked cabinet group untouched');
assert.equal(decorValue(base,'room:downstairs','wall'),undefined,'preview does not mutate committed snapshot');
assert.deepEqual(targetsFor({owner:'room:bedroom',room:'bedroom',scope:'one',part:'wall'}),['room:bedroom']);
assert.equal(roomFor('studyReading'),'study');
const all=applyPreset(base,presets.pink,{scope:'all',groups:['fabric']});
assert.equal(decorValue(all,'bedroomBed','fabric:quilt'),'blush');
assert.equal(decorValue(all,'studyReading','fabric:fabric'),'blush');
assert.ok(!Object.keys(all.values).some(x=>/screen|food|plant/i.test(x)));
console.log('Material scopes, independent parts, preset selection, locks and immutable preview passed.');
